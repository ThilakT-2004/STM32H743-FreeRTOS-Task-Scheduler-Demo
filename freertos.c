/**
  * @brief  Stack overflow hook
  *         Called by FreeRTOS if a task writes past the end of its stack.
  *         configCHECK_FOR_STACK_OVERFLOW must be 1 or 2 in FreeRTOSConfig.h
  *         Halts with IRQs disabled — attach debugger and inspect pcTaskName
  *         to identify which task overflowed.
  */
void vApplicationStackOverflowHook(TaskHandle_t xTask, char *pcTaskName)
{
  (void)xTask;
  (void)pcTaskName;
  __disable_irq();
  for (;;);
}

